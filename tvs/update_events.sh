#!/usr/bin/env bash
# Pulls today's events from the Mox Airtable and writes events.js for the
# HTML screen. Runs on the Pi; the API key never reaches the browser.
#
# Usage:  ./update_events.sh [output-file]
# Defaults (override with environment variables):
#   AIRTABLE_KEY_FILE  auth/airtable.com.txt  (same key file as events.sh)
#   MOX_EVENTS_OUT     web/events.js          (next to index.html)
#
# Paths are relative to this script's folder. Same requirements as events.sh:
# bash, curl, jq.
set -Eeuo pipefail

BASE_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$BASE_DIR"

export TZ="America/Los_Angeles"

BASE_ID="appkHZ2UvU6SouT5y"       # Mox base
TABLE_ID="tblqzGMNypqO3jftS"      # Events table
KEY_FILE="${AIRTABLE_KEY_FILE:-auth/airtable.com.txt}"
OUT="${1:-${MOX_EVENTS_OUT:-web/events.js}}"

# Only these statuses are hidden. Everything else (Confirmed, Recurring,
# To invoice, Invoiced, Paid, blank) is shown.
FORMULA="AND(
  {Start Date},
  IS_AFTER({Start Date}, DATEADD(NOW(), -1, 'days')),
  IS_BEFORE({Start Date}, DATEADD(NOW(), 1, 'days')),
  NOT(OR({Status} = 'Idea', {Status} = 'Maybe', {Status} = 'Cancelled', {Status} = 'Declined'))
)"

if [[ ! -s "$KEY_FILE" ]]; then
  echo "Missing Airtable API key at $KEY_FILE" >&2
  exit 1
fi
APIKEY="$(tr -d '[:space:]' < "$KEY_FILE")"

mkdir -p "$(dirname "$OUT")"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Fetch every page (Airtable returns 100 records per page).
offset=""
page=0
while :; do
  page=$((page + 1))
  args=(
    --data-urlencode "filterByFormula=$FORMULA"
    --data-urlencode "fields[]=Name"
    --data-urlencode "fields[]=Start Date"
    --data-urlencode "fields[]=End Date"
    --data-urlencode "fields[]=Floor Rollup (from Assigned Rooms)"
    --data-urlencode "sort[0][field]=Start Date"
    --data-urlencode "sort[0][direction]=asc"
  )
  [[ -n "$offset" ]] && args+=(--data-urlencode "offset=$offset")

  curl -fsS --connect-timeout 10 --max-time 30 --retry 2 --retry-delay 2 --retry-all-errors \
    -G "https://api.airtable.com/v0/$BASE_ID/$TABLE_ID" \
    -H "Authorization: Bearer $APIKEY" \
    "${args[@]}" > "$work/page$page.json"

  jq -e '.records | arrays' "$work/page$page.json" > /dev/null
  offset="$(jq -r '.offset // empty' "$work/page$page.json")"
  [[ -z "$offset" || $page -ge 20 ]] && break
done

NOW="$(date +%s)"
DAY_END="$(date -d 'tomorrow 00:00' +%s)"

# Keep events that haven't ended yet and start before midnight tonight.
# One entry per floor, so an event booked on floors 3 and 4 shows on both.
# Events with no floor ("Floor TBD" / no room) are left off.
events="$(jq -s --argjson now "$NOW" --argjson dayEnd "$DAY_END" '
  def ts: sub("\\.[0-9]+Z$"; "Z") | fromdateiso8601;
  [ .[].records[]
    | .fields as $f
    | ($f["Start Date"] | ts) as $start
    | (if $f["End Date"] then ($f["End Date"] | ts) else $start + 7200 end) as $end
    | select($end > $now and $start < $dayEnd and $end > $start)
    | ($f["Floor Rollup (from Assigned Rooms)"] // []
        | if type == "array" then join(" ") else tostring end
        | [scan("Floor ([1-4])") | .[0] | tonumber] | unique) as $floors
    | $floors[]
    | {
        floor: .,
        title: (($f.Name // "Untitled event") | gsub("^\\s+|\\s+$"; "")),
        start: $f["Start Date"],
        end: $f["End Date"]
      }
  ] | sort_by(.start)
' "$work"/page*.json)"

# Write atomically so the browser never reads a half-written file.
# "<\/" keeps an event title from closing the script tag.
tmp="$(mktemp "$OUT.XXXXXX")"
{
  echo "// Generated by update_events.sh from Airtable. Do not edit by hand."
  printf 'window.MOX_EVENTS_UPDATED = %s;\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ | jq -R .)"
  printf 'window.MOX_EVENTS = %s;\n' "$(printf '%s' "$events" | sed 's#</#<\\/#g')"
} > "$tmp"
chmod 644 "$tmp"
mv -f "$tmp" "$OUT"

echo "Wrote $(printf '%s' "$events" | jq length) floor listings to $OUT"
